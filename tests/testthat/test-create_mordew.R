test_that("create_mordew() names the package after the path", {
  path <- file.path(
    tempfile(),
    "runlog"
  )

  create_mordew(
    path
  )

  expect_equal(
    read.dcf(
      file.path(
        path,
        "DESCRIPTION"
      ),
      "Package"
    )[[1]],
    "runlog"
  )
})

test_that("create_mordew() refuses an existing path", {
  path <- tempfile()
  dir.create(
    path
  )

  expect_error(
    create_mordew(
      path
    ),
    "already exists"
  )
})

test_that("create_mordew(overwrite = TRUE) replaces an existing path", {
  path <- tempfile()
  dir.create(
    path
  )
  file.create(
    file.path(
      path,
      "old.R"
    )
  )

  create_mordew(
    path,
    overwrite = TRUE
  )

  expect_false(
    file.exists(
      file.path(
        path,
        "old.R"
      )
    )
  )
})

