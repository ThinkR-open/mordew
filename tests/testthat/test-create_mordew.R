test_that("create_mordew() checks the package before deploying it", {
  path <- tempfile()

  create_mordew(
    path
  )

  calls <- as.list(
    parse(
      file.path(
        path,
        "dev",
        "03_deploy.R"
      )
    )
  )
  expect_identical(
    deparse(
      calls[[1]]
    ),
    "devtools::check()"
  )
  expect_identical(
    Find(
      function(call) {
        identical(
          call[[1]],
          quote(
            mordew::add_dockerfile
          )
        )
      },
      calls
    ),
    quote(
      mordew::add_dockerfile()
    )
  )
})

