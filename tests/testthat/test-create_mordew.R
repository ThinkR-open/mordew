test_that("create_mordew() leaves no placeholder behind", {
  path <- tempfile()

  create_mordew(
    path
  )

  files <- list.files(
    path,
    recursive = TRUE,
    all.files = TRUE,
    full.names = TRUE
  )
  expect_false(
    any(
      grepl(
        "mordewexample",
        unlist(
          lapply(
            files,
            readLines
          )
        )
      )
    )
  )
})

